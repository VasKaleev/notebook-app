// Последовательная очередь для всех обращений к SQLite.
// Гарантирует, что в один момент выполняется только один запрос —
// это фиксит баг "третья заметка зависает" из прошлой версии.
//
// Как это работает: каждый вызов enqueue() ставится в цепочку промисов.
// Даже если UI запустит 10 запросов параллельно, они выполнятся по очереди.

let chain: Promise<unknown> = Promise.resolve();

export function enqueue<T>(task: () => Promise<T>): Promise<T> {
  // then(task, task) — выполняем и после ошибки, чтобы цепочка не сломалась
  const result = chain.then(task, task);
  // Сохраняем в цепочку «безопасную» версию — ошибка не остановит очередь
  chain = result.catch(() => {});
  return result;
}
